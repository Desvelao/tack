// normStatus lower-cases and treats '_' and '-' like spaces, so "in_progress",
// "in-progress" and "In Progress" rank the same.
func normStatus(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	return strings.Join(strings.Fields(strings.NewReplacer("_", " ", "-", " ").Replace(s)), " ")
}

var rankNorm = func() map[string]int {
	m := make(map[string]int, len(rank))
	for k, v := range rank {
		m[normStatus(k)] = v
	}
	return m
}()

const unknownRank = 4

// defaultWorkflow is the workflow `board.DefaultSpec` ships.
var defaultWorkflow = []string{"pending", "in_progress", "done", "failed"}

// Generate returns the text of a sample tack.yaml for the backend and
// location, plus notes about what was detected.
func Generate(o InitOptions) (string, []string, error) {
	if o.Backend == "" {
		return "", nil, fmt.Errorf("backend is required")
	}
	ex, err := backend.ExampleFor(o.Backend, o.Location)
	if err != nil {
		return "", nil, err
	}
	columns := boardColumns(ex.Statuses)
	spec := board.Spec{Unmapped: board.Append}
	for _, c := range columns {
		spec.Columns = append(spec.Columns, board.ColumnSpec{Name: c, Values: []string{c}})
	}
	if err := spec.Validate(); err != nil {
		return "", ex.Notes, fmt.Errorf("generated board is invalid: %w", err)
	}

	var b strings.Builder
	b.WriteString("# tack configuration")
	if o.Location != "" {
		b.WriteString(" for " + filepath.Base(o.Location))
	}
	b.WriteString("\n# Generated by `tack init`; edit freely. Reference: docs/config.md\n\n")
	b.WriteString("# Backends: each entry has a `type`, an optional `name` (default: type + position,\n")
	b.WriteString("# e.g. csv1) and the type's `options`. Cards show the name of their backend.\n")
	b.WriteString("backend:\n")
	if ex.Entry != "" {
		b.WriteString("  - " + strings.ReplaceAll(ex.Entry, "{{source}}", quote(sourceFor(o))) + "\n    options:\n")
	} else {
		fmt.Fprintf(&b, "  - type: %s\n    options:\n", o.Backend)
	}
	section := strings.ReplaceAll(ex.Section, "{{source}}", quote(sourceFor(o)))
	for _, line := range strings.Split(section, "\n") {
		if line == "" {
			b.WriteString("\n")
		} else {
			b.WriteString("      " + line + "\n")
		}
	}
	b.WriteString("\n# Audit trail of reloads and writes (press A in the board, or `tack audit`).\n")
	b.WriteString("# Kept in memory unless a file is set; .jsonl or .csv, relative to this file.\n")
	b.WriteString("# audit:\n#   file: audit.jsonl\n#   max_size: 1024    # KiB; past it the file is moved to audit.jsonl.1 (default: grows forever)\n")
	b.WriteString("\n# Actions: commands run on the selected task (press x in the board, or `tack run NAME ID`).\n")
	b.WriteString("# The command is a list, not a shell line; {id}, {title}, {description}, {status}, ... are\n")
	b.WriteString("# replaced by the task's values. mode: background (default) | interactive (owns the terminal).\n")
	b.WriteString("# Details of every run (command, stdin, output, times) can be kept with: action_log: {file: actions.jsonl}\n")
	b.WriteString("# actions:\n#   - {name: notify, command: [notify-send, \"tack #{id}\", \"{title}\"]}\n")
	b.WriteString("#   - {name: claude, key: c, mode: interactive, command: [claude, \"Work on task {id}: {title}\"]}\n")
	b.WriteString("# Marked cards (space, then x) run in the background, this many at once: action_max_parallel: 2\n")
	b.WriteString("\n# Hooks: commands started by events (task.create|update|delete[.success|.fail], task.moved,\n")
	b.WriteString("# task.appeared, task.disappeared, reload.ok|fail, action.started|finished|succeeded|failed).\n")
	b.WriteString("# `when` filters the event's task; {event} {old_status} {error} {source} are extra placeholders.\n")
	b.WriteString("# hooks:\n#   - {name: notify-high, on: [task.moved], when: \"priority=high\", command: [notify-send, \"#{id} {title}\", \"{old_status} -> {status}\"]}\n")
	b.WriteString("\nboard:\n")
	b.WriteString("  # Columns, left to right. `values` are the raw status values shown in a column;\n")
	b.WriteString("  # `write` (default: first value) is stored when a card is moved into it.\n")
	b.WriteString("  columns:\n")
	for _, c := range columns {
		fmt.Fprintf(&b, "    - {name: %s, values: [%s]}\n", quote(c), quote(c))
	}
	b.WriteString("  # Raw values no column claims: append (extra column each) | other | hide\n")
	b.WriteString("  unmapped: append\n")
	b.WriteString("  # Fields a plain filter term (`/` in the board, `list -q`) is matched against.\n")
	b.WriteString("  # Any field can also be targeted explicitly, e.g. priority=high or col:doing.\n")
	if others := otherFields(ex.Extras); len(others) > 0 {
		b.WriteString("  # Other fields: " + strings.Join(others, ", ") + "\n")
	}
	b.WriteString("  search: [id, title, description, notes]\n")
	b.WriteString("  # Display order of the cards in each column (the backends are never changed).\n")
	b.WriteString("  # `-` = descending; a list gives an explicit order. Press s / S in the board to try one.\n")
	b.WriteString("  # sort: [priority: [high, medium, low], -id]\n")
	return b.String(), ex.Notes, nil
}

// otherFields lists filterable fields that are not searched by plain text by default.
func otherFields(extras []string) []string {
	out := []string{"status", "priority", "type", "column"}
	seen := map[string]bool{}
	for _, f := range out {
		seen[f] = true
	}
	for _, e := range extras {
		if n := strings.ToLower(strings.ReplaceAll(strings.TrimSpace(e), " ", "_")); n != "" && !seen[n] {
			seen[n] = true
			out = append(out, n)
		}
	}
	return out
}

// defaultSources is the `source:` written when init gets no location.
var defaultSources = map[string]string{
	"json": "tasks.json", "jsonl": "tasks.jsonl", "yaml": "tasks.yaml", "sqlite": "tasks.db",
}

// sourceFor picks the `source:` value: relative to the output directory when possible.
func sourceFor(o InitOptions) string {
	loc := o.Location
	if loc == "" {
		if d, ok := defaultSources[strings.ToLower(o.Backend)]; ok {
			return d
		}
		return "tasks.csv"
	}
	if strings.Contains(loc, "://") {
		return loc
	}
	if o.Output == "" || o.Output == "-" {
		return loc
	}
	absLoc, err1 := filepath.Abs(loc)
	absOut, err2 := filepath.Abs(o.Output)
	if err1 != nil || err2 != nil {
		return loc
	}
	rel, err := filepath.Rel(filepath.Dir(absOut), absLoc)
	if err != nil {
		return absLoc
	}
	return filepath.ToSlash(rel)
}

// boardColumns turns observed raw statuses into an ordered, de-duplicated column list.
func boardColumns(statuses []string) []string {
	if len(statuses) == 0 {
		return append([]string(nil), defaultWorkflow...)
	}
	seen := map[string]bool{}
	var cols []string
	add := func(s string) {
		k := strings.ToLower(strings.TrimSpace(s))
		if k == "" || seen[k] {
			return
		}
		seen[k] = true
		cols = append(cols, s)
	}
	for _, s := range statuses {
		add(s)
	}
	// Data entirely on the default workflow: keep the missing canonical columns
	// so cards can be moved there (for example "failed").
	allCanon := true
	for _, s := range cols {
		isCanon := false
		for _, d := range defaultWorkflow {
			if strings.EqualFold(s, d) {
				isCanon = true
			}
		}
		allCanon = allCanon && isCanon
	}
	if allCanon {
		for _, d := range defaultWorkflow {
			add(d)
		}
	}
	r := func(s string) int {
		if v, ok := rankNorm[normStatus(s)]; ok {
			return v
		}
		return unknownRank
	}
	sort.SliceStable(cols, func(i, j int) bool { return r(cols[i]) < r(cols[j]) })
	return cols
}

// yamlWords are plain scalars YAML would read as null/bool, not as strings.
var yamlWords = map[string]bool{"null": true, "~": true, "true": true, "false": true, "yes": true, "no": true, "on": true, "off": true, "y": true, "n": true}

func quote(s string) string {
	// Bare words that YAML reads as null, bool or a number must stay quoted.
	if yamlWords[strings.ToLower(s)] || (s != "" && s[0] >= '0' && s[0] <= '9') {
		return strconv.Quote(s)
	}
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-' || r == '.' || r == '/')
	}) < 0 && s[0] != '-' && s[0] != '.' {
		return s
	}
	return strconv.Quote(s)
}
